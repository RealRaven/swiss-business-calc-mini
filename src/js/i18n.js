  let currentLang = localStorage.getItem(LANG_KEY) || 'de';
  if (!i18n[currentLang]) currentLang = 'de';

  function t(key) {
    const dict = i18n[currentLang];
    if (dict && dict[key]) return dict[key];
    const fallback = i18n['de'];
    if (fallback && fallback[key]) return fallback[key];
    return key;
  }

  function setLanguage(lang, skipApply) {
    if (!i18n[lang]) {
      console.warn('Language not found:', lang);
      return;
    }
    currentLang = lang;
    localStorage.setItem(LANG_KEY, lang);
    if (!skipApply) applyLanguage();
  }

  function getLanguage() { return currentLang; }

  function applyLanguage() {
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = val;
      } else if (el.tagName === 'OPTION') {
        el.textContent = val;
      } else {
        el.textContent = val;
      }
    });
    const langSelect = document.getElementById('lang-select');
    if (langSelect) langSelect.value = currentLang;
    document.documentElement.lang = currentLang === 'de' ? 'de' : currentLang === 'en' ? 'en' : currentLang === 'fr' ? 'fr' : 'it';
  }

  return {
    t: t,
    setLanguage: setLanguage,
    getLanguage: getLanguage,
    applyLanguage: applyLanguage,
    i18n: i18n,
    LANG_KEY: LANG_KEY
  };
